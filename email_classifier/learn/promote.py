"""Promotion of uniform LLM verdicts into deterministic rules (STU-822).

Offline only — never called from the request path. A learned rule freezes whatever the
LLM concluded, including a systematic misread, and once frozen the sender stops
escalating and stops producing `reasoning`. The criteria below are deliberately strict
and every emitted rule carries provenance so it can be traced and revoked.
"""

import re
from dataclasses import dataclass
from pathlib import Path

import yaml

from email_classifier.core.types import EmailInput
from email_classifier.learn.store import Observation
from email_classifier.stage1.rule_engine import Rule, matches

MIN_MESSAGES = 3
MIN_RUNS = 2
_NON_PROMOTABLE_ACTIONS = frozenset({"mark_for_delete", "escalate_to_llm"})

_HEADER = (
    "# Generated by `make promote` (STU-822) — do not edit by hand.\n"
    "# Learned rules are loaded between the hand-written rules and the catch-all,\n"
    "# so a hand-written rule always wins. Revoke with:\n"
    "#   python scripts/promote_rules.py --revoke <address>\n"
)


@dataclass(frozen=True)
class LearnedRule:
    from_address: str
    bucket: str
    action: str
    sample_size: int
    run_ids: list[str]
    promoted_at: str


@dataclass(frozen=True)
class Decision:
    from_address: str
    rule: LearnedRule | None
    reason: str


def rule_id(from_address: str) -> str:
    return "learned_" + re.sub(r"[^a-z0-9]+", "_", from_address.lower()).strip("_")


def _hand_written_match(from_address: str, hand_written: list[Rule]) -> Rule | None:
    """A hand-written rule that already claims this sender on address alone.

    Escalated emails matched only the catch-all when they were observed, so this only
    fires for rules added since — but those must keep priority, and emitting a learned
    duplicate would make the layering ambiguous.
    """
    probe = EmailInput(
        message_id="", thread_id="", from_address=from_address,
        subject="", headers={}, body_snippet="", date="",
    )
    for rule in hand_written:
        if rule.conditions and matches(probe, rule.conditions):
            return rule
    return None


def evaluate(
    observations: list[Observation],
    hand_written: list[Rule],
    blacklist: set[str],
    promoted_at: str,
    previously_promoted: dict[str, str] | None = None,
) -> list[Decision]:
    """One decision per observed sender, in first-seen order.

    `previously_promoted` maps rule id to its original `promoted_at`, so re-running the
    job does not churn the provenance of rules that were already there.
    """
    previously_promoted = previously_promoted or {}
    by_sender: dict[str, list[Observation]] = {}
    for obs in observations:
        by_sender.setdefault(obs.from_address, []).append(obs)

    decisions = []
    for sender, group in by_sender.items():
        decisions.append(
            _evaluate_sender(sender, group, hand_written, blacklist, promoted_at, previously_promoted)
        )
    return decisions


def _evaluate_sender(
    sender: str,
    group: list[Observation],
    hand_written: list[Rule],
    blacklist: set[str],
    promoted_at: str,
    previously_promoted: dict[str, str],
) -> Decision:
    def reject(reason: str) -> Decision:
        return Decision(from_address=sender, rule=None, reason=reason)

    if sender in blacklist:
        return reject("blacklisted")

    conflicting = _hand_written_match(sender, hand_written)
    if conflicting is not None:
        return reject(f"already covered by hand-written rule '{conflicting.id}'")

    # Distinct messages, not distinct observations: a redelivered notification must not
    # inflate the sample. Then distinct conversations, not distinct messages: a thread
    # is classified once (STU-944), so its messages share one judgement rather than
    # corroborating each other.
    by_message = {obs.message_id: obs for obs in group}
    by_thread = {obs.thread_id: obs for obs in by_message.values()}
    if len(by_thread) < MIN_MESSAGES:
        return reject(f"{len(by_thread)} distinct conversation(s) < {MIN_MESSAGES}")

    run_ids = sorted({obs.run_id for obs in by_thread.values()})
    if len(run_ids) < MIN_RUNS:
        return reject(f"{len(run_ids)} distinct run(s) < {MIN_RUNS}")

    verdicts = {(obs.bucket, obs.suggested_action) for obs in by_thread.values()}
    if len(verdicts) > 1:
        rendered = ", ".join(sorted(f"{b}/{a}" for b, a in verdicts))
        return reject(f"verdicts disagree: {rendered}")

    if any(obs.confidence != "high" for obs in by_thread.values()):
        return reject("not every observation is confidence: high")

    bucket, action = verdicts.pop()
    if action in _NON_PROMOTABLE_ACTIONS:
        return reject(f"action '{action}' is never auto-promoted")

    rid = rule_id(sender)
    return Decision(
        from_address=sender,
        rule=LearnedRule(
            from_address=sender,
            bucket=bucket,
            action=action,
            sample_size=len(by_thread),
            run_ids=run_ids,
            promoted_at=previously_promoted.get(rid, promoted_at),
        ),
        reason="promoted",
    )


def render(rules: list[LearnedRule]) -> str:
    payload = {
        "rules": [
            {
                "id": rule_id(r.from_address),
                "conditions": {"from_address": r.from_address},
                "bucket": r.bucket,
                "confidence": "medium",
                "action": r.action,
                "provenance": {
                    "sample_size": r.sample_size,
                    "run_ids": r.run_ids,
                    "promoted_at": r.promoted_at,
                },
            }
            for r in rules
        ]
    }
    return _HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)


def load_learned(path: Path) -> list[LearnedRule]:
    """Read back an existing learned.yaml, provenance included."""
    if not path.exists():
        return []
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return [
        LearnedRule(
            from_address=r["conditions"]["from_address"],
            bucket=r["bucket"],
            action=r["action"],
            sample_size=r["provenance"]["sample_size"],
            run_ids=r["provenance"]["run_ids"],
            promoted_at=r["provenance"]["promoted_at"],
        )
        for r in data.get("rules") or []
    ]


def load_blacklist(path: Path) -> set[str]:
    if not path.exists():
        return set()
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {address.lower() for address in data.get("blacklist") or []}


def save_blacklist(path: Path, blacklist: set[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Senders barred from promotion (STU-822). Managed by scripts/promote_rules.py.\n"
        + yaml.safe_dump({"blacklist": sorted(blacklist)}, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
